/// 百度网盘官方品牌标记(紧凑版 logo):蓝色云标 + 红色字标,两个官方 path 各带一条
/// `userSpaceOnUse` 线性渐变。几何照官方 `baidu-netdisk-logo-compact.svg` 的 viewBox 114×90 逐点转写。
///
/// 两个 path 都带 `fill-rule="evenodd"`,填色必须带 `FillStyle(eoFill: true)`。
/// 本类型只画 logo 本身,需要连着别的底一起画时由调用处叠加。
struct BaiduPanLogoMark: View {
    var size: CGFloat = Metrics.serverRowIconSize

    var body: some View {
        ZStack {
            BaiduPanCloudGlyph()
                .fill(BaiduPanGeometry.cloudGradient, style: FillStyle(eoFill: true))
            BaiduPanWordmarkGlyph()
                .fill(BaiduPanGeometry.wordmarkGradient, style: FillStyle(eoFill: true))
        }
        .frame(width: size, height: size * BaiduPanGeometry.aspect)
        .accessibilityHidden(true)
    }
}

struct BaiduPanCloudGlyph: Shape {
    func path(in rect: CGRect) -> Path {
        BaiduPanGeometry.cloudPath().applying(BaiduPanGeometry.fitTransform(for: rect))
    }
}

struct BaiduPanWordmarkGlyph: Shape {
    func path(in rect: CGRect) -> Path {
        BaiduPanGeometry.wordmarkPath().applying(BaiduPanGeometry.fitTransform(for: rect))
    }
}

